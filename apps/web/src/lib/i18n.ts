export const locale: 'en' | 'zh-TW' = navigator.languages.some((language) => /^zh(-(tw|hk|hant|mo))?/iu.test(language) && !/^zh-(cn|sg|hans)/iu.test(language))
  ? 'zh-TW'
  : 'en';

const table: Record<Key, string> = locale === 'zh-TW' ? zhTW : en;

export function t(key: Key, values: Record<string, string | number> = {}): string {
  return table[key].replaceAll(/\{(\w+)\}/gu, (_, name: string) => String(values[name] ?? ''));
}

export function formatSize(bytes: number): string {
  if (bytes < 1_024) return `${bytes} B`;
  if (bytes < 1_048_576) return `${(bytes / 1_024).toFixed(1)} KB`;
  return `${(bytes / 1_048_576).toFixed(1)} MB`;
}

export function formatClock(iso: string): string {
  return new Date(iso).toLocaleTimeString(locale, { hour: '2-digit', minute: '2-digit', hour12: false });
}
